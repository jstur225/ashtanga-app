function getMoonType(date) {
  return MOON_DAYS[String(date || '')] || '';
}

function getMoonIcon(date) {
  const type = getMoonType(date);
  return type ? `/images/moon-phase/${type === 'new' ? 'new-moon' : 'full-moon'}.png` : '';
}

